// Generates brand/js/icons.js: the small set of Lucide (ISC) icons the brand kit needs, as plain SVG strings,
// so the vanilla kit modules and the React site render the SAME glyphs without a React dependency.
//   node scripts/build-brand-icons.mjs
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const NAMES = ["globe", "chevron-down", "menu", "x", "play", "arrow-right", "trending-up", "mouse-pointer-click", "sparkles", "lightbulb",
  "package", "coffee", "filter", "cog", "flame", "cup-soda", "layers", "shopping-cart", "info", "check", "accessibility", "video",
  "clock", "send", "eye-off", "rotate-ccw", "lock", "circle-check", "shield-check", "message-square", "chart-column", "pin", "ban", "arrow-up", "arrow-down", "database", "triangle-alert", "pause", "chevron-right", "search"];
const dir = path.resolve("node_modules/lucide-react/dist/esm/icons");
const out = {};
for (const n of NAMES) {
  let file = `${n}.mjs`;
  const src = fs.readFileSync(path.join(dir, file), "utf8");
  const alias = /export \{ default \} from '\.\/([a-z-]+)\.mjs'/.exec(src); // some icons are aliases of another file
  if (alias) file = `${alias[1]}.mjs`;
  const mod = await import(pathToFileURL(path.join(dir, file)).href);
  out[n] = mod.__iconNode.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${v}"`).join(" ")}/>`).join("");
}
const body = `// GENERATED by scripts/build-brand-icons.mjs from lucide-react (ISC licence, https://lucide.dev). Do not edit by hand.
const ICONS = ${JSON.stringify(out, null, 2)};

/** SVG markup for a named icon. Decorative by default (aria-hidden); size in px. */
export function icon(name, size = 16, extra = "") {
  const inner = ICONS[name];
  if (!inner) throw new Error("brand icon not found: " + name);
  return \`<svg xmlns="http://www.w3.org/2000/svg" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false" \${extra}>\${inner}</svg>\`;
}
export const ICON_NAMES = Object.keys(ICONS);
`;
fs.writeFileSync("brand/js/icons.js", body);
console.log("brand/js/icons.js:", NAMES.length, "icons");
