// node scripts/selfservice-msgids.mjs [--write | --check]: the msgids of the P37 self-service strings, for the Control Plane theme mirror (/pricing/ and /start/ must say the same words).
// scripts/snapshots/selfservice-msgids.txt: one line per string, TAB separated: <key> <en (the gettext msgid)> <he> <es> <ru>. Strings are RAW (date tokens unresolved: {until} = the short last day,
// {lastDay} = the last day with the year, {n} = the store count of the plan; the Control Plane resolves them with the same date table as the launch offer). he / es / ru are machine drafts.
// --check fails when the file differs from the packs (so the list never goes stale); --write regenerates it.
import fs from "node:fs";
import path from "node:path";
import { loadTs, ROOT } from "./lib/load.mjs";

const FILE = path.join(ROOT, "scripts/snapshots/selfservice-msgids.txt");
const packs = { en: (await loadTs("src/i18n/ea/en.ts")).eaEn.ss, he: (await loadTs("src/i18n/ea/he.ts")).eaHe.ss, es: (await loadTs("src/i18n/ea/es.ts")).eaEs.ss, ru: (await loadTs("src/i18n/ea/ru.ts")).eaRu.ss };
const flat = (o, p = "", out = []) => { if (typeof o === "string") out.push([p, o]); else for (const k of Object.keys(o)) flat(o[k], p ? `${p}.${k}` : k, out); return out; };
const en = flat(packs.en);
const get = (o, k) => k.split(".").reduce((a, x) => a?.[x], o);
const lines = [
  "# P37 self-service string msgids (generated by scripts/selfservice-msgids.mjs; do not edit by hand). TAB separated: key, en (msgid), he, es, ru.",
  "# Raw strings: {until}/{lastDay} = date tokens resolved with the launch-offer date table (22:00 UTC end), {n} = store count of the plan. he/es/ru are machine drafts, not reviewed by native speakers.",
  ...en.map(([k, v]) => [`ss.${k}`, v, ...["he", "es", "ru"].map((l) => get(packs[l], k))].join("\t")),
];
const text = lines.join("\n") + "\n";
if (process.argv.includes("--write")) { fs.writeFileSync(FILE, text); console.log(`wrote ${en.length} msgids to ${path.relative(ROOT, FILE)}`); }
else {
  const have = fs.existsSync(FILE) ? fs.readFileSync(FILE, "utf8") : "";
  if (have !== text) { console.error(`FAIL: ${path.relative(ROOT, FILE)} is out of date (run: node scripts/selfservice-msgids.mjs --write)`); process.exit(1); }
  console.log(`ok: ${path.relative(ROOT, FILE)} matches the packs (${en.length} msgids)`);
}
