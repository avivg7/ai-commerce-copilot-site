// Writes brand/MANIFEST.json: SHA-256 and size of every file of the brand kit (the contract both surfaces verify).
//   node scripts/build-brand-manifest.mjs [--check]
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { ROOT } from "./lib/load.mjs";

const KIT = path.join(ROOT, "brand");
const files = [];
const walk = (d) => { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else if (e.name !== "MANIFEST.json" && e.name !== ".DS_Store") files.push(p); } };
walk(KIT);
files.sort();
const entries = {};
for (const f of files) {
  const buf = fs.readFileSync(f);
  entries[path.relative(KIT, f)] = { sha256: crypto.createHash("sha256").update(buf).digest("hex"), bytes: buf.length };
}
const manifest = { kit: "aicc-brand-kit", note: "GENERATED by scripts/build-brand-manifest.mjs. Verify with `node scripts/sync-brand-kit.mjs --verify <dir>`.", files: entries };
const json = JSON.stringify(manifest, null, 2) + "\n";
const target = path.join(KIT, "MANIFEST.json");
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (cur !== json) { console.error("brand/MANIFEST.json is stale: run `npm run brand:build`"); process.exit(1); }
  console.log(`brand manifest: up to date (${files.length} files)`);
} else { fs.writeFileSync(target, json); console.log(`brand/MANIFEST.json written (${files.length} files)`); }
