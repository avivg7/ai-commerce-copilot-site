#!/usr/bin/env bash
#
# AICC edge rehearsal: ONE persistent, disposable, production-like WordPress/WooCommerce Control Plane upstream.
#
#   scripts/rehearsal/cp-fixture.sh create    build the fixture (MySQL datadir, WordPress, WooCommerce, theme + plugin symlinks, seeds, users)
#   scripts/rehearsal/cp-fixture.sh start     start MySQL and the PHP web server (idempotent)
#   scripts/rehearsal/cp-fixture.sh stop      stop both (data kept)
#   scripts/rehearsal/cp-fixture.sh status
#   scripts/rehearsal/cp-fixture.sh stop-php|start-php|stop-mysql|start-mysql    (failure rehearsals: take only one half of the upstream down)
#   scripts/rehearsal/cp-fixture.sh cron      run due WP-Cron events once (what the production system cron does; DISABLE_WP_CRON is true)
#   scripts/rehearsal/cp-fixture.sh wp ...    run wp-cli against the fixture
#   scripts/rehearsal/cp-fixture.sh destroy   stop and delete everything under ~/aicc-rehearsal/cp (and the captured mail)
#
# It borrows only BINARIES (mysqld, php, wp-cli) and READS the Control Plane worktree (plugin + theme are symlinked, never copied; seeds are
# the worktree's own scripts). It writes nothing into any repo and nothing into any existing WordPress site, database or Local site.
# Ports: MySQL 127.0.0.1:18971, PHP 127.0.0.1:18982. Both loopback only. 8971-8983 (CP test suite / QA) and 9111-9114 (owner fixtures) are not used.
# Differences from production (be honest about them): php -S with PHP_CLI_SERVER_WORKERS (forked workers, not PHP-FPM), no opcache tuning,
# MySQL 8.4 from Local (production: managed MySQL/MariaDB), mail is captured to a directory instead of being sent.
set -uo pipefail

CP="${AICC_REHEARSAL_CP:-/Users/avivgerman/Local Sites/woo-recommendation-qa/aicc-control-plane-worktrees/cp2a-14-readiness-independence}"
HOME_DIR="${AICC_REHEARSAL_HOME:-$HOME/aicc-rehearsal}"
BASE="$HOME_DIR/cp"
MYSQL_PORT="${AICC_REHEARSAL_MYSQL_PORT:-18971}"
HTTP_PORT="${AICC_REHEARSAL_CP_PORT:-18982}"
DB_NAME="aicc_rehearsal_cp"
DB_PREFIX="rhsl_"
SITE_URL="https://www.copilt.org"
ADMIN_USER="rehearsal-admin";    ADMIN_PASS="Rehearsal-Admin-2026!"
CUST_USER="rehearsal-customer";  CUST_PASS="Rehearsal-Customer-2026!"
WP_VERSION="${AICC_REHEARSAL_WP_VERSION:-7.1.2}"
WC_VERSION="${AICC_REHEARSAL_WC_VERSION:-10.9.4}"
LOCAL_SERVICES="$HOME/Library/Application Support/Local/lightning-services"
MYSQLD="${AICC_REHEARSAL_MYSQLD:-$(ls "$LOCAL_SERVICES"/mysql-8.4.0+2/bin/*/bin/mysqld 2>/dev/null | head -1)}"
PHP="${AICC_REHEARSAL_PHP:-$(ls "$LOCAL_SERVICES"/php-8.2.29+0/bin/*/bin/php 2>/dev/null | head -1)}"
WP_CLI="${AICC_REHEARSAL_WP_CLI:-$(command -v wp || true)}"
MYSQL_BIN_DIR="$(dirname "$MYSQLD")"
# FAIL-CLOSED EGRESS (round 5): WordPress makes outbound HTTP requests on its own (Action Scheduler's async runner posts to https://www.copilt.org/wp-admin/admin-ajax.php, a REAL public host).
# Every PHP process of this fixture therefore (a) loads scripts/rehearsal/egress-guard.php (WordPress HTTP API: only www.copilt.org/copilt.org -> 127.0.0.1 and loopback; the rest is a WP_Error
# before any DNS lookup) and (b) on macOS runs under scripts/rehearsal/loopback-only.sb (the kernel denies every non-loopback connect). AICC_REHEARSAL_NO_SANDBOX=1 skips (b) only.
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
EGRESS_GUARD="$REPO_DIR/scripts/rehearsal/egress-guard.php"
SANDBOX=()
if [ "${AICC_REHEARSAL_NO_SANDBOX:-}" != 1 ] && command -v sandbox-exec >/dev/null 2>&1; then SANDBOX=(sandbox-exec -f "$REPO_DIR/scripts/rehearsal/loopback-only.sb"); fi
MYSQLADMIN="$MYSQL_BIN_DIR/mysqladmin"
SOCKET="$BASE/mysql.sock"

die() { echo "ERROR: $*" >&2; exit 1; }
wpc() { ${SANDBOX[@]+"${SANDBOX[@]}"} "$PHP" -d memory_limit=1024M -d "auto_prepend_file=$EGRESS_GUARD" "$WP_CLI" "$@" --path="$BASE/wp"; }
port_busy() { "$PHP" -r '$s=@fsockopen("127.0.0.1",(int)$argv[1],$e,$m,0.5); if($s){fclose($s); exit(0);} exit(1);' "$1"; }
need_tools() { [ -x "$MYSQLD" ] || die "mysqld not found (set AICC_REHEARSAL_MYSQLD)"; [ -x "$PHP" ] || die "php not found (set AICC_REHEARSAL_PHP)"; [ -n "$WP_CLI" ] || die "wp-cli not found"; [ -d "$CP/admin/wp-content/plugins/aicc-license-manager" ] || die "Control Plane worktree not found at $CP"; }

write_helpers() {
	# Fixture-only PHP helpers. They live under ~/aicc-rehearsal/cp/, never in a repo, and are generated here so the Control Plane tree stays untouched.
	mkdir -p "$BASE/wp/wp-content/mu-plugins" "$HOME_DIR/mail"
	[ -f "$BASE/echo-token" ] || "$PHP" -r 'echo bin2hex(random_bytes(12));' > "$BASE/echo-token"
	chmod 600 "$BASE/echo-token"

	cat > "$BASE/prepend.php" <<'PHP'
<?php
// auto_prepend_file for the rehearsal php -S: the OWNER MARKER. Every response generated by PHP carries X-Rehearsal-Upstream so a test can prove WordPress (not the static
// origin) answered. Fixture-only; production has no such header (the edge's access log records the upstream address instead).
if ( PHP_SAPI !== 'cli' ) {
	header( 'X-Rehearsal-Upstream: wordpress' );
	// Upstream request log (php -S does not log requests that a router script handles). Query values of secret-bearing parameters are redacted at write time.
	$uri = preg_replace( '/([?&](?:key|login|user_login|pass|password|pwd|pass1|pass2|token|code|nonce|_wpnonce|reset|license_key)=)[^&#]*/i', '$1REDACTED', (string) ( $_SERVER['REQUEST_URI'] ?? '' ) );
	@file_put_contents( dirname( __DIR__ ) . '/logs/cp-upstream.log', json_encode( array( 't' => gmdate( 'c' ), 'method' => $_SERVER['REQUEST_METHOD'] ?? '', 'uri' => $uri, 'peer' => $_SERVER['REMOTE_ADDR'] ?? '', 'xff' => $_SERVER['HTTP_X_FORWARDED_FOR'] ?? null, 'xfp' => $_SERVER['HTTP_X_FORWARDED_PROTO'] ?? null, 'xfh' => $_SERVER['HTTP_X_FORWARDED_HOST'] ?? null, 'host' => $_SERVER['HTTP_HOST'] ?? null, 'request_id' => $_SERVER['HTTP_X_REQUEST_ID'] ?? null, 'cookie_present' => isset( $_SERVER['HTTP_COOKIE'] ) ) ) . "\n", FILE_APPEND | LOCK_EX );
}
PHP

	cat > "$BASE/router.php" <<'PHP'
<?php
// Router for `php -S` (production would use nginx/Apache + PHP-FPM try_files). Real non-PHP files are served here (so they carry the owner marker, ETag and
// Last-Modified like a real web server); PHP files run as themselves; everything else goes to WordPress's front controller.
$root = $_SERVER['DOCUMENT_ROOT'];
$path = urldecode( parse_url( $_SERVER['REQUEST_URI'], PHP_URL_PATH ) );
$file = $root . $path;
if ( '/' !== $path && is_file( $file ) && '.php' !== strtolower( substr( $file, -4 ) ) && false === strpos( $path, '..' ) ) {
	static $types = array( 'css' => 'text/css', 'js' => 'application/javascript', 'svg' => 'image/svg+xml', 'png' => 'image/png', 'jpg' => 'image/jpeg', 'jpeg' => 'image/jpeg', 'gif' => 'image/gif', 'webp' => 'image/webp', 'woff2' => 'font/woff2', 'woff' => 'font/woff', 'ico' => 'image/x-icon', 'json' => 'application/json', 'txt' => 'text/plain', 'mp4' => 'video/mp4', 'vtt' => 'text/vtt', 'map' => 'application/json' );
	$ext = strtolower( pathinfo( $file, PATHINFO_EXTENSION ) );
	$mtime = filemtime( $file );
	$etag  = '"' . dechex( $mtime ) . '-' . dechex( filesize( $file ) ) . '"';
	require_once __DIR__ . '/prepend.php';
	header( 'Content-Type: ' . ( $types[ $ext ] ?? 'application/octet-stream' ) );
	header( 'ETag: ' . $etag );
	header( 'Last-Modified: ' . gmdate( 'D, d M Y H:i:s', $mtime ) . ' GMT' );
	if ( ( $_SERVER['HTTP_IF_NONE_MATCH'] ?? '' ) === $etag ) { http_response_code( 304 ); return true; }
	header( 'Content-Length: ' . filesize( $file ) );
	readfile( $file );
	return true;
}
if ( '/' !== $path && is_dir( $file ) && is_file( rtrim( $file, '/' ) . '/index.php' ) ) { // /wp-admin/ -> wp-admin/index.php (nginx: index index.php)
	$script = rtrim( $path, '/' ) . '/index.php';
	$_SERVER['SCRIPT_NAME'] = $_SERVER['PHP_SELF'] = $script; $_SERVER['SCRIPT_FILENAME'] = $root . $script;
	chdir( dirname( $root . $script ) );
	require_once __DIR__ . '/prepend.php';
	require $root . $script;
	return true;
}
if ( '/' !== $path && is_file( $file ) ) { return false; } // an existing .php entry point (wp-login.php, wp-cron.php, xmlrpc.php, wp-admin/admin-ajax.php): php -S runs it as itself
require_once __DIR__ . '/prepend.php'; // php -S runs auto_prepend_file only for scripts it executes itself, not for files a router includes
require $root . '/index.php';
PHP

	cat > "$BASE/wp/wp-content/mu-plugins/aicc-rehearsal.php" <<'PHP'
<?php
/**
 * Plugin Name: AICC edge rehearsal fixture helpers (FIXTURE ONLY, never part of any repo)
 * 1. Mail capture: wp_mail() writes an .eml file under AICC_REHEARSAL_MAIL_DIR instead of sending, so a password-reset link can be read.
 * 2. Request echo: GET ?__rehearsal_echo=<token> on any WordPress-routed URL returns the request headers PHP received and the client address the Control Plane
 *    resolves (AICC_LM_Client_IP::get()). The token is in ~/aicc-rehearsal/cp/echo-token; without it the parameter is ignored.
 */
defined( 'ABSPATH' ) || exit;
add_filter( 'pre_wp_mail', function ( $null, $atts ) {
	$dir = defined( 'AICC_REHEARSAL_MAIL_DIR' ) ? AICC_REHEARSAL_MAIL_DIR : '';
	if ( '' === $dir || ! is_dir( $dir ) ) { return $null; }
	$to  = is_array( $atts['to'] ) ? implode( ', ', $atts['to'] ) : (string) $atts['to'];
	$hd  = is_array( $atts['headers'] ) ? implode( "\n", $atts['headers'] ) : (string) $atts['headers'];
	$eml = "To: {$to}\nSubject: {$atts['subject']}\nX-Captured-At: " . gmdate( 'c' ) . "\n" . ( '' !== $hd ? $hd . "\n" : '' ) . "\n" . (string) $atts['message'] . "\n";
	file_put_contents( $dir . '/' . gmdate( 'Ymd-His' ) . '-' . substr( md5( $eml . wp_rand() ), 0, 8 ) . '.eml', $eml );
	return true;
}, 10, 2 );
add_action( 'plugins_loaded', function () {
	// Failure injection for the 5xx tests: ?__rehearsal_fail=<token>&__rehearsal_code=500|502|503 answers that status with a body that LOOKS like an internal error
	// (fake stack trace, fake internal paths) so a test can prove the edge never lets such a body reach the visitor. ?__rehearsal_sleep=<token>&__rehearsal_secs=N delays the answer.
	if ( defined( 'AICC_REHEARSAL_ECHO_TOKEN' ) && isset( $_GET['__rehearsal_fail'] ) && hash_equals( AICC_REHEARSAL_ECHO_TOKEN, (string) $_GET['__rehearsal_fail'] ) ) {
		$code = isset( $_GET['__rehearsal_code'] ) ? (int) $_GET['__rehearsal_code'] : 500;
		status_header( $code );
		header( 'Content-Type: text/html; charset=UTF-8' );
		header( 'X-Upstream-Secret-Detail: db-host=10.1.2.3' );
		echo "<html><body>Fatal error: Uncaught Exception in /srv/www/wp-content/plugins/secret/UPSTREAM-LEAK-MARKER.php:42\nStack trace: #0 mysql://root@10.1.2.3/prod</body></html>";
		exit;
	}
	if ( defined( 'AICC_REHEARSAL_ECHO_TOKEN' ) && isset( $_GET['__rehearsal_sleep'] ) && hash_equals( AICC_REHEARSAL_ECHO_TOKEN, (string) $_GET['__rehearsal_sleep'] ) ) {
		sleep( max( 0, min( 60, (int) ( $_GET['__rehearsal_secs'] ?? 5 ) ) ) );
		header( 'Content-Type: text/plain' );
		echo 'slept';
		exit;
	}
	if ( ! isset( $_GET['__rehearsal_echo'] ) || ! defined( 'AICC_REHEARSAL_ECHO_TOKEN' ) || ! hash_equals( AICC_REHEARSAL_ECHO_TOKEN, (string) $_GET['__rehearsal_echo'] ) ) { return; }
	$h = array();
	foreach ( $_SERVER as $k => $v ) { if ( 0 === strpos( $k, 'HTTP_' ) ) { $h[ strtolower( str_replace( '_', '-', substr( $k, 5 ) ) ) ] = $v; } }
	nocache_headers();
	header( 'Content-Type: application/json' );
	echo wp_json_encode( array(
		'remote_addr' => $_SERVER['REMOTE_ADDR'] ?? null,
		'cp_client_ip' => class_exists( 'AICC_LM_Client_IP' ) ? AICC_LM_Client_IP::get() : null,
		'https_server_var' => $_SERVER['HTTPS'] ?? null,
		'is_ssl' => is_ssl(),
		'host' => $_SERVER['HTTP_HOST'] ?? null,
		'request_uri' => $_SERVER['REQUEST_URI'] ?? null,
		'home_url' => home_url( '/' ),
		'headers' => $h,
	) );
	exit;
}, 99 );
PHP
}

create() {
	need_tools
	[ ! -d "$BASE/wp" ] || die "fixture already exists at $BASE (use destroy first)"
	port_busy "$MYSQL_PORT" && die "port $MYSQL_PORT is busy"
	port_busy "$HTTP_PORT" && die "port $HTTP_PORT is busy"
	mkdir -p "$BASE/mysql" "$BASE/wp" "$HOME_DIR/logs" "$HOME_DIR/mail" "$HOME_DIR/run"
	chmod 700 "$BASE"
	echo "== MySQL datadir ($MYSQLD)"
	"$MYSQLD" --initialize-insecure --datadir="$BASE/mysql/data" --basedir="$(dirname "$MYSQL_BIN_DIR")" > "$BASE/mysql/init.log" 2>&1 || { tail "$BASE/mysql/init.log" >&2; die "mysqld --initialize-insecure failed"; }
	start_mysql || die "mysql did not start"
	"$PHP" -r '$d=new mysqli("127.0.0.1","root","",null,(int)$argv[1]); if($d->connect_errno){fwrite(STDERR,$d->connect_error); exit(1);} $d->query("CREATE DATABASE IF NOT EXISTS `".$argv[2]."` DEFAULT CHARACTER SET utf8mb4");' "$MYSQL_PORT" "$DB_NAME" || die "create database failed"
	echo "== WordPress $WP_VERSION"
	wpc core download --version="$WP_VERSION" --skip-plugins --skip-themes >/dev/null 2>&1 || die "wp core download failed"
	write_helpers
	local TOKEN; TOKEN="$(cat "$BASE/echo-token")"
	# wp-config: home/siteurl as constants (NOT written to QA), https derived from X-Forwarded-Proto exactly as docs/cutover/runbook.md section 1.1 prescribes,
	# the edge as the only trusted proxy, system cron instead of WP-Cron.
	wpc config create --dbname="$DB_NAME" --dbuser=root --dbpass='' --dbhost="127.0.0.1:$MYSQL_PORT" --dbprefix="$DB_PREFIX" --skip-check --force --extra-php >/dev/null <<PHP || die "wp config create failed"
define( 'WP_HOME', '$SITE_URL' );
define( 'WP_SITEURL', '$SITE_URL' );
if ( ( \$_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '' ) === 'https' ) { \$_SERVER['HTTPS'] = 'on'; }
define( 'AICC_LM_TRUSTED_PROXIES', array( '127.0.0.1' ) ); // the edge's address as the upstream sees it (the rehearsal edge dials 127.0.0.1)
define( 'AICC_LM_OPERATOR_CIDRS', '127.0.0.1/32' ); // IPv4 loopback = the operators of the rehearsal (never throttled); ::1 is an ordinary client, so the login throttle can be exercised from it
define( 'DISABLE_WP_CRON', true );
define( 'AICC_LM_ALLOW_DEV_SECRET_BOOTSTRAP', true ); // fixture only: a local dev value for the activation-proof / entitlement-webhook secrets
define( 'WP_DEBUG', false );
define( 'AICC_REHEARSAL_FIXTURE', true );
define( 'AICC_REHEARSAL_MAIL_DIR', '$HOME_DIR/mail' );
define( 'AICC_REHEARSAL_ECHO_TOKEN', '$TOKEN' );
PHP
	wpc core install --url="$SITE_URL" --title="AICC Control Plane (edge rehearsal fixture)" --admin_user="$ADMIN_USER" --admin_password="$ADMIN_PASS" --admin_email=rehearsal-admin@example.test --skip-email >/dev/null || die "wp core install failed"
	ln -sfn "$CP/admin/wp-content/plugins/aicc-license-manager" "$BASE/wp/wp-content/plugins/aicc-license-manager"
	ln -sfn "$CP/admin/wp-content/themes/aicc-admin" "$BASE/wp/wp-content/themes/aicc-admin"
	echo "== WooCommerce $WC_VERSION + plugin + theme"
	wpc plugin install woocommerce --version="$WC_VERSION" --activate >/dev/null 2>&1 || die "woocommerce install failed (needs wp-cli cache or network)"
	wpc plugin activate aicc-license-manager >/dev/null || die "plugin activate failed"
	wpc theme install storefront --version=4.6.2 >/dev/null 2>&1 || die "storefront parent theme install failed (the child theme needs it; wp-cli cache has 4.6.2)"
	wpc theme activate aicc-admin >/dev/null || die "theme activate failed"
	wpc option update permalink_structure '/%postname%/' >/dev/null
	wpc option update woocommerce_coming_soon no >/dev/null 2>&1
	wpc option update woocommerce_store_pages_only no >/dev/null 2>&1
	wpc wc tool run install_pages --user=1 >/dev/null 2>&1 || true
	wpc rewrite flush >/dev/null 2>&1
	echo "== seeds (the worktree's own idempotent scripts)"
	( cd "$CP" && AICC_BOOTSTRAP_APPLY=1 wpc eval-file scripts/bootstrap-commercial-products.php | tail -3 )
	( cd "$CP" && AICC_ACCOUNT_POLICY_APPLY=1 wpc eval-file scripts/configure-account-required-checkout.php | tail -3 )
	( cd "$CP" && AICC_LEGAL_SEED_APPLY=1 wpc eval-file scripts/seed-legal-documents.php | tail -6 )
	wpc user create "$CUST_USER" rehearsal-customer@example.test --role=customer --user_pass="$CUST_PASS" >/dev/null
	wpc rewrite flush >/dev/null 2>&1
	echo "== created. home/siteurl: $(wpc option get home) / $(wpc option get siteurl)"
	start_php
	status
}

start_mysql() {
	port_busy "$MYSQL_PORT" && "$MYSQLADMIN" --protocol=TCP -h 127.0.0.1 -P "$MYSQL_PORT" -u root ping >/dev/null 2>&1 && { echo "mysql already up"; return 0; }
	"$MYSQLD" --datadir="$BASE/mysql/data" --basedir="$(dirname "$MYSQL_BIN_DIR")" --socket="$SOCKET" --port="$MYSQL_PORT" --bind-address=127.0.0.1 \
		--pid-file="$BASE/mysql/mysqld.pid" --mysqlx=OFF --skip-log-bin --log-error="$BASE/mysql/error.log" > /dev/null 2>&1 &
	for _ in $(seq 1 60); do "$MYSQLADMIN" --protocol=TCP -h 127.0.0.1 -P "$MYSQL_PORT" -u root ping >/dev/null 2>&1 && return 0; sleep 1; done
	return 1
}

start_php() {
	if port_busy "$HTTP_PORT"; then echo "php already up on $HTTP_PORT"; return 0; fi
	[ -d "$BASE/wp" ] || die "no fixture (run create)"
	write_helpers
	( cd "$BASE/wp" && PHP_CLI_SERVER_WORKERS="${AICC_REHEARSAL_PHP_WORKERS:-8}" nohup ${SANDBOX[@]+"${SANDBOX[@]}"} "$PHP" -d memory_limit=512M -d expose_php=On -d display_errors=0 -d log_errors=1 -d "error_log=$HOME_DIR/logs/cp-php-error.log" \
		-d "auto_prepend_file=$EGRESS_GUARD" -S "127.0.0.1:$HTTP_PORT" -t "$BASE/wp" "$REPO_DIR/scripts/rehearsal/fixture-router.php" < /dev/null >> "$HOME_DIR/logs/cp-php-access.log" 2>&1 & echo $! > "$BASE/php.pid" ) > /dev/null 2>&1
	for _ in $(seq 1 30); do [ "$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:$HTTP_PORT/?rest_route=/" 2>/dev/null)" = "200" ] && { echo "php up on 127.0.0.1:$HTTP_PORT (pid $(cat "$BASE/php.pid"))"; return 0; }; sleep 1; done
	tail -5 "$HOME_DIR/logs/cp-php-access.log" >&2; die "php server did not answer"
}

stop_php() { [ -f "$BASE/php.pid" ] && kill "$(cat "$BASE/php.pid")" 2>/dev/null; pkill -f "php.*-S 127.0.0.1:$HTTP_PORT" 2>/dev/null; rm -f "$BASE/php.pid"; return 0; }
stop_mysql() { "$MYSQLADMIN" --protocol=TCP -h 127.0.0.1 -P "$MYSQL_PORT" -u root shutdown >/dev/null 2>&1; return 0; }

status() {
	echo "CP fixture: $BASE"
	port_busy "$MYSQL_PORT" && echo "  mysql  127.0.0.1:$MYSQL_PORT  UP   (db $DB_NAME, prefix $DB_PREFIX)" || echo "  mysql  127.0.0.1:$MYSQL_PORT  DOWN"
	port_busy "$HTTP_PORT" && echo "  php -S 127.0.0.1:$HTTP_PORT  UP   (docroot $BASE/wp)" || echo "  php -S 127.0.0.1:$HTTP_PORT  DOWN"
	echo "  admin    $ADMIN_USER / $ADMIN_PASS"
	echo "  customer $CUST_USER / $CUST_PASS"
	echo "  mail dir $HOME_DIR/mail   logs $HOME_DIR/logs/cp-php-*.log"
}

case "${1:-}" in
	create)  create ;;
	start)   need_tools; start_mysql || die "mysql failed"; start_php; status ;;
	stop)    need_tools; stop_php; stop_mysql; sleep 1; status ;;
	status)  need_tools; status ;;
	stop-php)    need_tools; stop_php; echo "php stopped" ;;
	start-php)   need_tools; start_php ;;
	stop-mysql)  need_tools; stop_mysql; echo "mysql stop requested" ;;
	start-mysql) need_tools; start_mysql && echo "mysql up" ;;
	cron)    need_tools; wpc cron event run --due-now ;;
	wp)      need_tools; shift; wpc "$@" ;;
	destroy) need_tools; stop_php; stop_mysql; sleep 2; rm -f "$BASE/wp/wp-content/plugins/aicc-license-manager" "$BASE/wp/wp-content/themes/aicc-admin"; rm -rf "$BASE"; rm -f "$HOME_DIR"/mail/*.eml; echo "destroyed" ;;
	*)       sed -n 3,14p "$0"; exit 2 ;;
esac
