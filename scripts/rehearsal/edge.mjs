export function oldTargetSafety(text) {
  const code = text.split("\n").filter((l) => !/^\s*#/.test(l)).join("\n");
  const errs = [];
  if (!/^\s*local_certs\s*$/m.test(code)) errs.push("no local_certs");
  if (/\bacme_ca\b|\bacme_dns\b|^\s*email\b|letsencrypt|zerossl/m.test(code)) errs.push("public ACME configuration");
  if (/api\.copilt\.org/.test(code)) errs.push("api.copilt.org present");
  return errs;
}
