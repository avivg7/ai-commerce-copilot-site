// Generator + runner library for the rehearsal edge (see rehearsal.mjs for the CLI).
import fs from "node:fs";
import path from "node:path";
import { spawn } from "node:child_process";
import { P, HOME, INSTANCES, WP_UPSTREAM, OPERATOR_DEFAULT, REPO, ensureDirs, readPid, alive, portListening, waitFor, now, sh, caddyVersion } from "./lib.mjs";


export function settings(argvOverride, argv = process.argv.slice(2)) {
  const opt = (k, d) => { const i = argv.indexOf(`--${k}`); return i >= 0 ? argv[i + 1] : d; };
  const name = opt("name", "edge");
  const base = INSTANCES[name] || { name, httpPort: 18080, httpsPort: 18443, admin: "127.0.0.1:12021", operatorCidrs: OPERATOR_DEFAULT };
  return {
    name,
    httpPort: Number(opt("http-port", base.httpPort)),
    httpsPort: Number(opt("https-port", base.httpsPort)),
    admin: opt("admin", base.admin),
    upstream: opt("upstream", WP_UPSTREAM),
    staticRoot: opt("static-root", P.current),
    operatorCidrs: opt("operator-cidrs", base.operatorCidrs),
    wpTimeout: opt("wp-timeout", "60s"),
    variant: opt("variant", ""),
    template: opt("template", P.template),
    ...(argvOverride || {}),
  };
}
const caddyfilePath = (s) => path.join(P.generated, s.name === "edge" ? "Caddyfile" : `Caddyfile.${s.name}`);

function replaceRegion(text, begin, end, body) {
  const a = text.indexOf(begin), b = text.indexOf(end);
  if (a < 0 || b < 0 || b < a) throw new Error(`template region ${begin} .. ${end} not found`);
  return text.slice(0, a) + body + text.slice(b + end.length);
}
function replaceSnippet(text, name, body) {
  const re = new RegExp(`\\(${name}\\) \\{\\n(?:(?!\\}\\n)[^\\n]*\\n)*\\}\\n`);
  if (!re.test(text)) throw new Error(`template snippet (${name}) not found`);
  return text.replace(re, `(${name}) {\n${body}\n}\n`);
}

/** Template -> rehearsal Caddyfile. Production semantics (routing, redirects, headers, logging, error handling) are NOT touched: only the marked global region and two hook snippets. */
export function generate(s) {
  ensureDirs();
  let t = fs.readFileSync(s.template, "utf8");
  const globals = [
    "\t# BEGIN GLOBAL OPTIONS (rehearsal: generated by scripts/rehearsal/rehearsal.mjs; production keeps the template's block)",
    "\tlocal_certs",
    "\tskip_install_trust",
    `\tadmin ${s.admin}`,
    `\thttp_port ${s.httpPort}`,
    `\thttps_port ${s.httpsPort}`,
    ...(s.httpsPort !== 443 ? ["\t# high-port instances bind loopback only; :80/:443 cannot (macOS allows unprivileged low ports only on the wildcard address)", "\tdefault_bind 127.0.0.1 [::1]"] : []),
    `\tstorage file_system ${P.caddyData}`,
    "\torder abort before redir",
    ...((s.variant || "").split("+").includes("no-certs") ? ["\t# VARIANT no-certs: Caddy manages no certificate at all (rehearses the window before a certificate exists)", "\tauto_https disable_certs"] : []),
    "\tservers {",
    "\t\ttimeouts {",
    "\t\t\tread_header 10s",
    "\t\t\tread_body 60s",
    "\t\t\tidle 2m",
    "\t\t}",
    "\t\tmax_header_size 16KB",
    "\t}",
    "\tlog {",
    `\t\toutput file ${P.logs}/error.log {`,
    "\t\t\troll_size 20MiB",
    "\t\t\troll_keep 5",
    "\t\t\troll_keep_for 720h",
    "\t\t}",
    "\t\tformat json",
    "\t\tlevel INFO",
    "\t}",
    "\t# END GLOBAL OPTIONS",
  ].join("\n");
  t = replaceRegion(t, "\t# BEGIN GLOBAL OPTIONS", "# END GLOBAL OPTIONS", globals.replace(/^\t/, "\t") ).replace(/# END GLOBAL OPTIONS(?!\n)/, "# END GLOBAL OPTIONS");
  t = replaceSnippet(t, "aicc_tls", "\ttls internal");
  t = replaceSnippet(t, "aicc_site_hook", [
    "\t# rehearsal only: the wildcard listener (macOS lets an unprivileged process bind :80/:443 only on the wildcard address) must not serve the LAN.",
    "\t@aicc_non_loopback not remote_ip 127.0.0.0/8 ::1/128",
    "\tabort @aicc_non_loopback",
  ].join("\n"));
  if (s.httpsPort !== 443) t = t.replaceAll("https://www.copilt.org", `https://www.copilt.org:${s.httpsPort}`);
  const variants = (s.variant || "").split("+").filter(Boolean);
  let pre = "";
  // TEMPORARY config variants for the CP "Watch demo" test; never part of the template
  if (variants.includes("cp-home")) pre += "\t@variant_cp_home path /\n\thandle @variant_cp_home {\n\t\timport to_wordpress\n\t}\n";
  if (variants.includes("block-demo")) pre += "\t@variant_block_demo path_regexp variant_block_demo ^/demo/.*$\n\thandle @variant_block_demo {\n\t\terror 404\n\t}\n";
  if (pre) t = t.replace("\t# BEGIN GENERATED: routing\n", "\t# BEGIN GENERATED: routing\n" + pre);
  const out = caddyfilePath(s);
  fs.writeFileSync(out, t);
  return { file: out, text: t };
}

/** Refuse to run anything that could talk to a public CA, answer for api.copilt.org or proxy somewhere that is not this Mac. */
export function safetyCheck(s, text) {
  const errs = [];
  const code = text.split("\n").filter((l) => !/^\s*#/.test(l)).join("\n");
  const up = s.upstream.replace(/^https?:\/\//, "").split(":")[0];
  if (!["127.0.0.1", "localhost", "::1", "[::1]"].includes(up)) errs.push(`upstream ${s.upstream} is not loopback`);
  if (!/^\s*local_certs\s*$/m.test(code)) errs.push("global option local_certs is missing");
  if (/\bacme_ca\b|\bacme_dns\b|\bacme_eab\b|^\s*email\b|\bissuer\s+(acme|zerossl)|letsencrypt|zerossl|\bdns\s+\w+|on_demand_tls/m.test(code)) errs.push("public ACME / DNS-challenge / email configuration present");
  if (/(^|[\s,])(https?:\/\/)?api\.copilt\.org/m.test(code)) errs.push("an api.copilt.org address is present");
  const sites = [...code.matchAll(/^([^\s#{}][^{\n]*?)\s*\{\s*$/gm)].map((m) => m[1]).filter((x) => !x.startsWith("("));
  const httpsSites = sites.filter((a) => a.split(",").some((x) => !x.trim().startsWith("http://")));
  const tlsImports = (code.match(/^\s*import aicc_tls\s*$/gm) || []).length;
  if (httpsSites.length !== tlsImports) errs.push(`${httpsSites.length} site blocks serve https but ${tlsImports} import aicc_tls`);
  if (!/\(aicc_tls\) \{\n\s*tls internal\s*\n\}/.test(code)) errs.push("(aicc_tls) is not `tls internal`");
  if (/^\s*(default_)?bind\s/m.test(code) && !/^\s*(default_)?bind\s+(127\.0\.0\.1|\[::1\])(\s+(127\.0\.0\.1|\[::1\]))*\s*$/m.test(code)) errs.push("non-loopback bind");
  if (!(s.staticRoot.startsWith(HOME))) errs.push(`static root ${s.staticRoot} is outside ${HOME}`);
  return errs;
}

export function envFor(s) {
  return {
    ...process.env,
    AICC_STATIC_ROOT: s.staticRoot,
    AICC_WP_UPSTREAM: s.upstream,
    AICC_OPERATOR_CIDRS: s.operatorCidrs,
    AICC_LOG_DIR: P.logs,
    AICC_WP_TIMEOUT: s.wpTimeout,
    XDG_DATA_HOME: path.join(HOME, "caddy/xdg-data"),
    XDG_CONFIG_HOME: P.caddyConfig,
  };
}

function guarded(s) {
  const { file, text } = generate(s);
  const errs = safetyCheck(s, text);
  if (errs.length) { console.error("REFUSING:\n  " + errs.join("\n  ")); process.exit(3); }
  return file;
}
export async function validate(s, quiet) {
  const file = guarded(s);
  const r = sh(P.caddy, ["validate", "--config", file, "--adapter", "caddyfile"], { env: envFor(s) });
  if (!quiet) console.log(r.out.split("\n").filter((l) => !l.startsWith("{")).join("\n") || r.out);
  return { ok: r.code === 0, out: r.out, file };
}
export function adapt(s) {
  const file = guarded(s);
  const r = sh(P.caddy, ["adapt", "--config", file, "--adapter", "caddyfile", "--pretty"], { env: envFor(s) });
  return { ok: r.code === 0, json: r.stdout, err: r.out.slice(r.stdout.length), file };
}

export async function start(s, { quiet } = {}) {
  ensureDirs();
  const pidFile = path.join(P.run, `${s.name}.pid`);
  if (alive(readPid(s.name))) { if (!quiet) console.log(`${s.name}: already running (pid ${readPid(s.name)})`); return { pid: readPid(s.name), ms: 0 }; }
  if (!fs.existsSync(s.staticRoot)) { console.error(`static root ${s.staticRoot} missing: run \`rehearsal.mjs release\` first`); process.exit(2); }
  const v = await validate(s, true);
  if (!v.ok) { console.error(v.out); process.exit(1); }
  if (await portListening(s.httpsPort)) { console.error(`port ${s.httpsPort} is already in use`); process.exit(1); }
  const log = fs.openSync(path.join(P.logs, `caddy-${s.name}.stdout.log`), "a");
  const t0 = now();
  const child = spawn(P.caddy, ["run", "--config", v.file, "--adapter", "caddyfile", "--pidfile", pidFile], { env: envFor(s), detached: true, stdio: ["ignore", log, log] });
  child.unref();
  fs.writeFileSync(pidFile, String(child.pid));
  const ms = await waitFor(async () => (await portListening(s.httpsPort)) && (await portListening(s.httpPort)), 30000, 50);
  if (ms < 0) { console.error("caddy did not open its ports; see " + path.join(P.logs, `caddy-${s.name}.stdout.log`)); process.exit(1); }
  const live = await liveConfigCheck(s);
  if (!quiet) console.log(`${s.name}: started pid ${child.pid}, listening on :${s.httpPort}/:${s.httpsPort} after ${now() - t0} ms; ${live}`);
  return { pid: child.pid, ms: now() - t0 };
}
async function liveConfigCheck(s) {
  try {
    const r = await fetch(`http://${s.admin}/config/`, { headers: { Origin: `http://${s.admin}` } });
    const j = await r.text();
    const bad = /"module":"acme"|"module":"zerossl"|"ca":"https?:\/\//.test(j);
    const internal = (j.match(/"module":"internal"/g) || []).length;
    if (bad) throw new Error("live config contains an ACME issuer");
    return `live config: no ACME issuer, ${internal} internal-issuer policy(ies)`;
  } catch (e) { return `live config check failed: ${e.message}`; }
}
export async function stop(s, { quiet } = {}) {
  const pid = readPid(s.name);
  if (!alive(pid)) { if (!quiet) console.log(`${s.name}: not running`); return { ms: 0 }; }
  const t0 = now();
  process.kill(pid, "SIGTERM");
  const ms = await waitFor(async () => !alive(pid), 15000, 50);
  if (ms < 0) process.kill(pid, "SIGKILL");
  if (!quiet) console.log(`${s.name}: stopped in ${now() - t0} ms`);
  return { ms: now() - t0 };
}
export async function reload(s, { quiet } = {}) {
  const v = await validate(s, true);
  if (!v.ok) { console.error(v.out); process.exit(1); }
  const t0 = now();
  const r = sh(P.caddy, ["reload", "--config", v.file, "--adapter", "caddyfile", "--address", s.admin, "--force"], { env: envFor(s) });
  if (r.code !== 0) { console.error(r.out); process.exit(1); }
  if (!quiet) console.log(`${s.name}: reloaded in ${now() - t0} ms`);
  return { ms: now() - t0 };
}
export async function status(s) {
  const pid = readPid(s.name);
  const up = alive(pid);
  console.log(`caddy: ${caddyVersion()}`);
  console.log(`${s.name}: ${up ? "RUNNING pid " + pid : "stopped"}; http :${s.httpPort} ${(await portListening(s.httpPort)) ? "open" : "closed"}; https :${s.httpsPort} ${(await portListening(s.httpsPort)) ? "open" : "closed"}; admin ${s.admin}`);
  console.log(`static root: ${s.staticRoot} -> ${fs.existsSync(s.staticRoot) ? fs.realpathSync(s.staticRoot) : "(missing)"}`);
  console.log(`upstream: ${s.upstream} ${(await portListening(Number(s.upstream.split(":")[1]))) ? "UP" : "DOWN"}; operator CIDRs: ${s.operatorCidrs}`);
  console.log(`root CA: ${P.rootCrt} ${fs.existsSync(P.rootCrt) ? "(present)" : "(created on first start)"}`);
}

export function release() {
  ensureDirs();
  const out = path.join(REPO, "out");
  if (!fs.existsSync(path.join(out, "index.html"))) { console.error("out/ missing: AICC_BASE_PATH=\"\" SITE_URL=https://www.copilt.org npm run build"); process.exit(2); }
  const sha = sh("git", ["-C", REPO, "rev-parse", "--short", "HEAD"]).stdout.trim();
  const id = `${new Date().toISOString().replace(/[-:]/g, "").replace(/\.\d+Z$/, "Z")}-${sha}`;
  const dir = path.join(P.releases, id);
  fs.mkdirSync(dir, { recursive: true });
  const r = sh("rsync", ["-a", "--delete", "--exclude", ".DS_Store", out + "/", dir + "/"]);
  if (r.code !== 0) { console.error(r.out); process.exit(1); }
  fs.copyFileSync(P.fiftyxx, path.join(dir, "50x.html"));
  sh("bash", ["-c", `cd "${dir}" && find . -type f -print0 | sort -z | xargs -0 shasum -a 256 > "../${id}.sha256"`]);
  const tmp = path.join(P.releases, `.current.${process.pid}`);
  fs.rmSync(tmp, { force: true });
  fs.symlinkSync(dir, tmp);
  fs.renameSync(tmp, P.current); // atomic: rename(2) over the existing symlink
  console.log(`release ${id}\n  current -> ${dir}\n  demo sha256 ${sh("shasum", ["-a", "256", path.join(dir, "demo/aicc-demo.mp4")]).stdout.slice(0, 16)}...`);
  return dir;
}

export function launchdPlist(s) {
  const label = "org.copilt.aicc-rehearsal-edge";
  const env = envFor(s);
  const keys = ["AICC_STATIC_ROOT", "AICC_WP_UPSTREAM", "AICC_OPERATOR_CIDRS", "AICC_LOG_DIR", "AICC_WP_TIMEOUT", "XDG_DATA_HOME", "XDG_CONFIG_HOME"];
  const file = guarded(s);
  const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>${label}</string>
  <key>ProgramArguments</key><array><string>${P.caddy}</string><string>run</string><string>--config</string><string>${file}</string><string>--adapter</string><string>caddyfile</string></array>
  <key>EnvironmentVariables</key><dict>
${keys.map((k) => `    <key>${k}</key><string>${env[k]}</string>`).join("\n")}
  </dict>
  <key>KeepAlive</key><true/>
  <key>RunAtLoad</key><true/>
  <key>ThrottleInterval</key><integer>2</integer>
  <key>StandardOutPath</key><string>${P.logs}/caddy-launchd.stdout.log</string>
  <key>StandardErrorPath</key><string>${P.logs}/caddy-launchd.stdout.log</string>
  <key>WorkingDirectory</key><string>${HOME}</string>
</dict></plist>
`;
  const out = path.join(P.run, `${label}.plist`);
  fs.writeFileSync(out, plist);
  return { out, label };
}


/**
 * Rollback rehearsal: a Caddyfile for the OLD target (the saved GitHub Pages site) behind the same hostnames. Standalone, rehearsal-only, never part of the template.
 * Serves ~/aicc-rehearsal/old-target/site (the saved old-www-home.html as index.html + robots.txt, sitemap.xml and the 404 page fetched read-only from the live old site),
 * apex and http -> 301 https://www.copilt.org{uri}, everything else the old site does not have -> its own 404 page. Same ports/admin as the edge instance it replaces.
 */
export function generateOldTarget(s) {
  ensureDirs();
  const site = path.join(HOME, "old-target/site");
  const text = `# REHEARSAL ONLY: stand-in for the old GitHub Pages target (what a DNS revert would serve)
{
	local_certs
	skip_install_trust
	admin ${s.admin}
	http_port ${s.httpPort}
	https_port ${s.httpsPort}
	${s.httpsPort !== 443 ? "default_bind 127.0.0.1 [::1]" : "# wildcard listener (see aicc_site_hook in the real template)"}
	storage file_system ${P.caddyData}
	auto_https disable_redirects
	log {
		output file ${P.logs}/old-target-error.log {
			roll_size 20MiB
			roll_keep 3
		}
		format json
	}
}
(old_guard) {
	@old_non_loopback not remote_ip 127.0.0.0/8 ::1/128
	abort @old_non_loopback
}
http://copilt.org, https://copilt.org, http://www.copilt.org {
	import old_guard
	tls internal
	redir https://www.copilt.org{uri} 301
}
www.copilt.org {
	import old_guard
	tls internal
	root * ${site}
	file_server
	handle_errors {
		rewrite * /404.html
		file_server {
			status {http.error.status_code}
		}
	}
}
`;
  const file = path.join(P.generated, `Caddyfile.old-target${s.name === "edge" ? "" : "." + s.name}`);
  fs.writeFileSync(file, text);
  return { file, text };
}
export function oldTargetSafety(text) {
  const code = text.split("\n").filter((l) => !/^\s*#/.test(l)).join("\n");
  const errs = [];
  if (!/^\s*local_certs\s*$/m.test(code)) errs.push("no local_certs");
  if (/\bacme_ca\b|\bacme_dns\b|^\s*email\b|letsencrypt|zerossl/m.test(code)) errs.push("public ACME configuration");
  if (/api\.copilt\.org/.test(code)) errs.push("api.copilt.org present");
  return errs;
}
