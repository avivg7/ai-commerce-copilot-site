// Generates brand/i18n/strings.json from the typed dictionaries (the single source of the words). Run by `npm run brand:build`.
//   node scripts/build-brand-strings.mjs [--check]   (--check fails if the committed file is stale)
import fs from "node:fs";
import path from "node:path";
import { loadDictionaries, loadFallbacks, loadTs, ROOT } from "./lib/load.mjs";

const dicts = await loadDictionaries();
const { LOCALE_META, LOCALES } = await loadTs("src/i18n/config.ts");
const fb = await loadFallbacks();
const KIT_SETS = ["demo", "rules", "dash", "ask", "flows", "loop", "faqSearch"];
const out = { _generated: "GENERATED by scripts/build-brand-strings.mjs from src/i18n/*.ts. Do not edit by hand. A kit string set with _fallback: true is English text on a page of another language (render it lang=en dir=ltr).", locales: LOCALES };
for (const l of LOCALES) {
  const d = dicts[l];
  out[l] = {
    dir: LOCALE_META[l].dir,
    htmlLang: LOCALE_META[l].htmlLang,
    lang: {
      label: d.common.language.label,
      current: d.common.language.current,
      names: Object.fromEntries(LOCALES.map((x) => [x, LOCALE_META[x].endonym])),
      short: Object.fromEntries(LOCALES.map((x) => [x, LOCALE_META[x].short])),
    },
    header: {
      siteName: d.meta.siteName,
      nav: { product: d.common.nav.product, pricing: d.common.nav.pricing, questions: d.common.nav.questions, account: d.common.nav.account, menu: d.common.nav.menu },
      signIn: d.brand.signIn,
      getStarted: d.common.getStarted,
      accessibility: d.common.a11y.button,
    },
    // The footer's headings and link labels (the shared header/footer contract is brand/content/header-nav.json: order and targets; these are its words).
    footer: {
      productHeading: d.common.footer.productHeading,
      trustHeading: d.common.footer.trustHeading,
      languageHeading: d.common.footer.languageHeading,
      links: {
        product: d.common.pageNames.product,
        pricing: d.common.pageNames.pricing,
        questions: d.common.pageNames.questions,
        dataTrust: d.common.pageNames.dataTrust,
        privacy: d.common.pageNames.privacy,
        terms: d.common.pageNames.terms,
        refund: d.common.pageNames.refund,
        dpa: d.common.pageNames.dpa,
        accessibility: d.common.pageNames.accessibility,
      },
    },
    watchDemo: d.brand.watchDemo,
    chips: [d.brand.chips.orders, d.brand.chips.clicks, d.brand.chips.recs, d.brand.chips.insights, d.brand.chips.bundles],
    modal: d.brand.modal,
    // Kit string sets. A set that is not translated yet is English with _fallback: true: the module marks its container lang="en" dir="ltr".
    ...Object.fromEntries(KIT_SETS.map((k) => [k, fb[l].includes(k) ? { ...d[k], _fallback: true } : d[k]])),
    fbtHeading: d.home.demo.title,
    fbtLead: d.home.demo.lead,
    // Units of this locale that are English fallback (Stage 2 translates them): kit sets above plus the headings.
    needsTranslation: fb[l].filter((u) => KIT_SETS.includes(u) || u === "home.demo"),
  };
}
const labelsSrc = JSON.parse(fs.readFileSync(path.join(ROOT, "brand/content/replica-labels.json"), "utf8"));
out.replicaLabels = labelsSrc.labels; // the plugin-admin labels the kit marks lang="en" on non-English pages (the Control Plane's PHP ports read this list)
const json = JSON.stringify(out, null, 2) + "\n";
const file = path.join(ROOT, "brand/i18n/strings.json");
// The vanilla kit modules need the same list as a module (a browser cannot import JSON without an import attribute).
const labelsJs = `// GENERATED by scripts/build-brand-strings.mjs from brand/content/replica-labels.json. Do not edit by hand.\n// Real plugin-admin labels (English). On es/ru pages every occurrence in the replicas is wrapped lang="en" dir="ltr" at the leaf (see motion.js labeler()).\nexport const REPLICA_LABELS = ${JSON.stringify(labelsSrc.labels)};\n`;
const labelsFile = path.join(ROOT, "brand/js/replica-labels.js");
if (process.argv.includes("--check") && (!fs.existsSync(labelsFile) || fs.readFileSync(labelsFile, "utf8") !== labelsJs)) { console.error("brand/js/replica-labels.js is stale: run `npm run brand:build`"); process.exit(1); }
if (!process.argv.includes("--check")) fs.writeFileSync(labelsFile, labelsJs);
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (cur !== json) { console.error("brand/i18n/strings.json is stale: run `npm run brand:build`"); process.exit(1); }
  console.log("brand strings: up to date");
} else {
  fs.writeFileSync(file, json);
  console.log(`brand/i18n/strings.json written (${json.length} bytes, ${LOCALES.length} locales)`);
}
